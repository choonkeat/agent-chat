package main

import (
	"bytes"
	"fmt"
	"os"
	"strings"
	"testing"
)

// agentSeesFile is a saved copy of exactly what the agent receives for a few
// sample messages. It exists to be READ by a person: the 0.19.0 bug (the
// Message-style text pasted above the user's words, so the agent answered the
// style instead of the user) passed every test, because the tests asserted
// that layout. One look at the text the agent received would have shown it.
//
// TestAgentSees fails whenever the real output stops matching this file, so a
// change to what the agent sees cannot slip in unnoticed: it must be accepted
// with `make agent-sees`, which rewrites the file, and the change then shows
// in the commit diff. `make publish` shows how the file changed since the
// last release and asks for a yes before publishing.
const agentSeesFile = "testdata/agent-sees.txt"

type agentSeesCase struct {
	title  string
	render func() string
}

func agentSeesCases() []agentSeesCase {
	style := "Reply for a reader with ADHD: lead with the next action, number multi-step work, cut all preamble, recap, and closers."
	attached := []FileRef{{Path: "/tmp/agent-chat-uploads/pasted-207-lines.txt", Type: "text/plain", Size: 2048}}
	return []agentSeesCase{
		{"check_messages: typed message + message style + attachment (full guidance, sent every 10th delivery)", func() string {
			guidanceDeliveries.Store(0)
			return composeCheckMessagesResult(nil, []UserMessage{{
				Text: "Discuss how do we support this in swe-swe? Through agent-chat?", Template: style, Files: attached,
			}})
		}},
		{"send_message reply: typed + message style (short guidance, the other 9 deliveries)", func() string {
			guidanceDeliveries.Store(1)
			return userRespondedText([]UserMessage{{Text: "Yes, go ahead", Template: style}})
		}},
		{"check_messages: two typed messages in one batch, same style", func() string {
			guidanceDeliveries.Store(1)
			return composeCheckMessagesResult(nil, []UserMessage{
				{Text: "Fix the login page", Template: style},
				{Text: "this one too: the signup page", Template: style},
			})
		}},
		{"check_messages: voice message, no style (full guidance)", func() string {
			guidanceDeliveries.Store(0)
			return composeCheckMessagesResult(nil, []UserMessage{{Text: "\U0001f3a4 what's the status"}})
		}},
		{"check_messages: nothing waiting", func() string {
			return composeCheckMessagesResult(nil, nil)
		}},
	}
}

func renderAgentSees() []byte {
	var b bytes.Buffer
	b.WriteString("# What the agent receives for sample messages (generated by agent_sees_test.go).\n")
	b.WriteString("# Read it as the agent would: is the user's message clearly separate from everything else?\n")
	b.WriteString("# After a deliberate change, regenerate with: make agent-sees\n")
	for i, c := range agentSeesCases() {
		fmt.Fprintf(&b, "\n===== %d. %s =====\n\n%s\n", i+1, c.title, strings.TrimRight(c.render(), "\n"))
	}
	return b.Bytes()
}

func TestAgentSees(t *testing.T) {
	saved := guidanceDeliveries.Load()
	defer guidanceDeliveries.Store(saved)

	got := renderAgentSees()
	if os.Getenv("UPDATE_AGENT_SEES") == "1" {
		if err := os.MkdirAll("testdata", 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(agentSeesFile, got, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(agentSeesFile)
	if err != nil {
		t.Fatalf("%v — create it with: make agent-sees", err)
	}
	if !bytes.Equal(got, want) {
		t.Fatalf("what the agent receives changed. Read the new text below as the agent would;\n"+
			"if it is right, accept it with `make agent-sees` and commit %s.\n\n%s", agentSeesFile, got)
	}
}
